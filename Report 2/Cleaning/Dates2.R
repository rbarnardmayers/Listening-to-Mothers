  mutate(YEARBIRTH = as.numeric(YEARBIRTH),
         BIRTHDATE_M_NUM = case_when(BIRTHDATE_M == 1 ~ '01',
                                     BIRTHDATE_M == 2 ~ '02', 
                                     BIRTHDATE_M == 3 ~ '03', 
                                     BIRTHDATE_M == 4 ~ '04', 
                                     BIRTHDATE_M == 5 ~ '05', 
                                     BIRTHDATE_M == 6 ~ '06', 
                                     BIRTHDATE_M == 7 ~ '07', 
                                     BIRTHDATE_M == 8 ~ '08', 
                                     BIRTHDATE_M == 9 ~ '09', 
                                     BIRTHDATE_M == 10 ~ '10', 
                                     BIRTHDATE_M == 11 ~ '11', 
                                     BIRTHDATE_M == 12 ~ '12'),
         BIRTHDATE_D = case_when(nchar(BIRTHDATE_D) == 1 ~ paste0("0",BIRTHDATE_D),
                                 TRUE ~ as.character(BIRTHDATE_D)),
         BIRTHDATE_T = paste0(YEARBIRTH,BIRTHDATE_M_NUM,BIRTHDATE_D),
         BIRTHDATE = as.Date(BIRTHDATE_T, "%Y%m%d"), 
         Q2_ConnectionDate = case_when(grepl("/", xLastConnectionDate) ~ gsub("/","", xLastConnectionDate),
                                       TRUE ~ as.character(xLastConnectionDate)),
         Q1_ConnectionDate = case_when(grepl("/", LastConnectionDate) ~ gsub("/","", LastConnectionDate),
                                       TRUE ~ as.character(LastConnectionDate)),
         Q2_ConnectionDate = as.Date(Q2_ConnectionDate, "%Y%m%d"),
         Q1_ConnectionDate = as.Date(Q1_ConnectionDate, "%Y%m%d"), 
         SURVEYDATE_Q2 = case_when(Q2FIELD == "#NULL!" ~ Q1_ConnectionDate, 
                                   TRUE ~ Q2_ConnectionDate),
         SURVEYDATE_Q1 = case_when(is.na(Q1_ConnectionDate) ~ Q2_ConnectionDate, 
                                   TRUE ~ Q1_ConnectionDate),
         
         TIME_SINCE_BIRTH = difftime(SURVEYDATE_Q2, BIRTHDATE, units = "weeks"),
         TIME_SINCE_BIRTH = as.numeric(TIME_SINCE_BIRTH), 
         TIME_SINCE_BIRTH2 = round(TIME_SINCE_BIRTH),
         TIME_SINCE_BIRTH_MONTH = floor(TIME_SINCE_BIRTH2/4),
         TIME_SINCE_BIRTH_MONTH2 = case_when(TIME_SINCE_BIRTH_MONTH < 3 ~ 3,
                                             TIME_SINCE_BIRTH_MONTH > 24 ~ 24, 
                                             TRUE ~ TIME_SINCE_BIRTH_MONTH),
         TIME_SINCE_BIRTH_QUART = case_when(TIME_SINCE_BIRTH_MONTH <= 2 ~ "< 2 months", 
                                            TIME_SINCE_BIRTH_MONTH <= 5 ~ "3-5 months", 
                                            TIME_SINCE_BIRTH_MONTH <= 8 ~ "6-8 months", 
                                            TIME_SINCE_BIRTH_MONTH <= 11 ~ "9-11 months", 
                                            TIME_SINCE_BIRTH_MONTH <= 14 ~ "12 - 14 months",
                                            TIME_SINCE_BIRTH_MONTH <= 17 ~ "15 - 17 months", 
                                            TIME_SINCE_BIRTH_MONTH <= 20 ~ "18 - 20 months", 
                                            TIME_SINCE_BIRTH_MONTH <= 23 ~ "21 - 23 months", 
                                            TIME_SINCE_BIRTH_MONTH > 23 ~ "24+ months"),
         TIME_SINCE_BIRTH_HALF = case_when(TIME_SINCE_BIRTH_MONTH <= 2 ~ "< 2 months", 
                                           TIME_SINCE_BIRTH_MONTH <= 5 ~ "3-5 months", 
                                           TIME_SINCE_BIRTH_MONTH <= 11 ~ "6-11 months", 
                                           TIME_SINCE_BIRTH_MONTH <= 17 ~ "12 - 17 months",
                                           TIME_SINCE_BIRTH_MONTH <= 23 ~ "18 - 23 months", 
                                           TIME_SINCE_BIRTH_MONTH > 23 ~ "24+ months"),
         TIME_SINCE_BIRTH_HALF_2 = case_when(TIME_SINCE_BIRTH_MONTH <= 5 ~ "0 - 5 months", 
                                             TIME_SINCE_BIRTH_MONTH <= 11 ~ "6 - 11 months", 
                                             TIME_SINCE_BIRTH_MONTH <= 17 ~ "12 - 17 months",
                                             TIME_SINCE_BIRTH_MONTH <= 23 ~ "18 - 23 months", 
                                             TIME_SINCE_BIRTH_MONTH > 23 ~ "24+ months"),
         MONTH_6 = case_when(TIME_SINCE_BIRTH >= 24 ~ 1, TRUE ~ 0),
         
         TIME_SINCE_BIRTH_Q1 = difftime(SURVEYDATE_Q1, BIRTHDATE, units = "weeks"),
         TIME_SINCE_BIRTH_Q1 = as.numeric(TIME_SINCE_BIRTH_Q1), 
         TIME_SINCE_BIRTH2_Q1 = round(TIME_SINCE_BIRTH_Q1),
         TIME_SINCE_BIRTH_MONTH_Q1 = floor(TIME_SINCE_BIRTH2_Q1/4),
         TIME_SINCE_BIRTH_MONTH2_Q1 = case_when(TIME_SINCE_BIRTH_MONTH_Q1 < 3 ~ 3,
                                             TIME_SINCE_BIRTH_MONTH_Q1 > 24 ~ 24, 
                                             TRUE ~ TIME_SINCE_BIRTH_MONTH_Q1),
         TIME_SINCE_BIRTH_HALF_Q1 = case_when(TIME_SINCE_BIRTH_MONTH_Q1 <= 2 ~ "< 2 months", 
                                           TIME_SINCE_BIRTH_MONTH_Q1 <= 5 ~ "3-5 months", 
                                           TIME_SINCE_BIRTH_MONTH_Q1 <= 11 ~ "6-11 months", 
                                           TIME_SINCE_BIRTH_MONTH_Q1 <= 17 ~ "12 - 17 months",
                                           TIME_SINCE_BIRTH_MONTH_Q1 <= 23 ~ "18 - 23 months", 
                                           TIME_SINCE_BIRTH_MONTH_Q1 > 23 ~ "24+ months"),
         TIME_SINCE_BIRTH_HALF_2_Q1 = case_when(TIME_SINCE_BIRTH_MONTH_Q1 <= 5 ~ "0 - 5 months", 
                                             TIME_SINCE_BIRTH_MONTH_Q1 <= 11 ~ "6 - 11 months", 
                                             TIME_SINCE_BIRTH_MONTH_Q1 <= 17 ~ "12 - 17 months",
                                             TIME_SINCE_BIRTH_MONTH_Q1 <= 23 ~ "18 - 23 months", 
                                             TIME_SINCE_BIRTH_MONTH_Q1 > 23 ~ "24+ months"),
         MONTH_6 = case_when(TIME_SINCE_BIRTH_Q1 >= 24 ~ 1, TRUE ~ 0))
